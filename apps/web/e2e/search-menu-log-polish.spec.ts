import { expect, test } from '@playwright/test'

for (const reducedMotion of ['no-preference', 'reduce'] as const) {
  test(`search and filters retain their geometry (${reducedMotion})`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion })
    await page.goto('/skeleton-contract-test?editor=search-menu-log')
    const search = page.getByRole('searchbox')
    await search.fill('runtime')
    await expect(search).toHaveAttribute('aria-busy', 'true')
    const bounds = await search.boundingBox()
    const results = page.getByTestId('stable-results')
    const resultBounds = await results.boundingBox()
    await expect(results).toHaveText('All resources')
    const icon = page.getByTestId('search-field-icon')
    await expect(icon).toHaveClass(/animate-spin/)
    await expect(icon).toHaveCSS('animation-name', reducedMotion === 'reduce' ? 'none' : 'spin')
    expect(await search.boundingBox()).toEqual(bounds)
    await expect(search).toBeEditable()
    await page.getByRole('button', { name: 'Complete search' }).click()
    await expect(results).toHaveText('runtime')
    expect(await results.boundingBox()).toEqual(resultBounds)
    const filter = page.getByRole('button', { name: /^Filters/ })
    const filterBounds = await filter.boundingBox()
    const filterIcon = await filter.locator('svg').boundingBox()
    const filterLabel = await filter.getByText('Filters', { exact: true }).boundingBox()
    expect(filterIcon!.x - filterBounds!.x).toBeCloseTo(
      filterBounds!.x + filterBounds!.width - filterLabel!.x - filterLabel!.width,
      0
    )
    await filter.click()
    await page.getByRole('checkbox', { name: 'Running resources' }).check()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(filter).toBeFocused()
    await expect(filter).toHaveAccessibleName('Filters (3)')
    expect(await filter.boundingBox()).toEqual(filterBounds)
    const summary = page.getByRole('group', { name: 'Active filters' })
    await expect(summary).toBeVisible()
    expect((await results.boundingBox())!.y).toBeGreaterThan((await summary.boundingBox())!.y)
    await page.getByRole('button', { name: 'Remove State filter' }).click()
    await expect(filter).toBeFocused()
    await expect(filter).toHaveAccessibleName('Filters')
    expect(await results.boundingBox()).toEqual(resultBounds)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0)
  })

  test(`menus fade without movement and restore keyboard focus (${reducedMotion})`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion })
    await page.goto('/skeleton-contract-test?editor=search-menu-log')
    const trigger = page.getByRole('button', { name: 'Resource actions' })
    const bounds = await trigger.boundingBox()
    await trigger.focus()
    await page.keyboard.press('Enter')
    const menu = page.getByRole('menu')
    await expect(menu).toBeVisible()
    await expect(menu).toHaveCSS('transition-property', reducedMotion === 'reduce' ? 'none' : 'opacity')
    await expect(menu).toHaveCSS('transform', 'none')
    await page.keyboard.press('Escape')
    await expect(menu).toBeHidden()
    await expect(trigger).toBeFocused()
    expect(await trigger.boundingBox()).toEqual(bounds)
    await page.keyboard.press('Enter')
    await page.getByRole('menuitem', { name: 'Inspect resource' }).focus()
    await page.keyboard.press('Enter')
    await expect(menu).toBeHidden()
    await expect(trigger).toBeFocused()
    const select = page.getByRole('combobox', { name: 'Preview choice' })
    const selectBounds = await select.boundingBox()
    await select.click()
    const list = page.locator('[data-slot="select-content"]')
    await expect(list).toHaveCSS('transition-duration', reducedMotion === 'reduce' ? '0s' : '0.12s')
    await expect(list).toHaveCSS('transform', 'none')
    await page.getByRole('option', { name: 'Second', exact: true }).click()
    await expect(select).toHaveText('Second')
    await expect(select).toBeFocused()
    expect(await select.boundingBox()).toEqual(selectBounds)
  })

  test(`live logs preserve reading position and resume following (${reducedMotion})`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion })
    await page.goto('/skeleton-contract-test?editor=search-menu-log')
    const output = page.getByLabel('Log output')
    const atBottom = () => output.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)
    await expect.poll(atBottom).toBeLessThan(2)
    await output.evaluate(node => {
      node.scrollTop = 200
      node.dispatchEvent(new Event('scroll'))
    })
    const latest = page.getByRole('button', { name: 'Latest output' })
    await expect(latest).toBeVisible()
    await page.getByRole('button', { name: 'Append output' }).click()
    const bounds = await output.boundingBox()
    expect(await output.evaluate(node => node.scrollTop)).toBe(200)
    const pageScroll = await page.evaluate(() => scrollY)
    await latest.click()
    await expect(latest).toBeHidden()
    await expect(output).toBeFocused()
    await expect.poll(atBottom).toBeLessThan(2)
    expect(await output.boundingBox()).toEqual(bounds)
    expect(await page.evaluate(() => scrollY)).toBe(pageScroll)
    await page.getByRole('button', { name: 'Append output' }).click()
    await expect.poll(atBottom).toBeLessThan(2)
    await page.screenshot({
      path: `/tmp/rebroid-follow-${test.info().project.name}-${reducedMotion}.png`,
      fullPage: true
    })
  })
}
